import assert from "node:assert/strict";
import { allocate, exitPrices, fuelReturn, harvestIncome, lootPlan, opportunities, orderScenario, productionPlan, shoppingList, stressTrade, volumeCap } from "../apps/web/lib/money-workbench.ts";
const row = (id, itemId, extra = {}) => ({ id, itemId, name: id, kind: "BAZAAR", cost: 10, profit: 2, roi: .2, limit: 100, confidence: .8, stale: false, requirement: null, href: "/", ...extra });
const plan = allocate([row("a", "A"), row("a2", "A"), row("b", "B"), row("stale", "C", { stale: true }), row("locked", "D", { requirement: "Collection" })], 100, 20, .5, 5);
assert.equal(plan.spent, 80);
assert.equal(plan.basket.length, 2);
assert.equal(plan.profit, 16);
assert.equal(allocate([row("a", "A")], 10, 20, 1, 5).spent, 0);
assert.equal(allocate([row("a", "A", { cost: Infinity })], 100, 0, 1, 5).spent, 0);
const order = orderScenario(100, 110, 10, .0125, 1, 1);
assert.equal(order.cost, 1010);
assert.ok(Math.abs(order.profit - 66.375) < 1e-6);
assert.ok(Math.abs(orderScenario(100, order.breakEven, 10, .0125, 1, 0).profit) < 1e-6);
assert.equal(orderScenario(100, 110, 10, 1, 0, 0).breakEven, null);
assert.equal(volumeCap(168000, 84000, 2, .01, 10, 10000), 10);
assert.equal(volumeCap(168000, 84000, 2, .01, 10, 20), 2);
assert.equal(volumeCap(0, 84000, 2, .01, 10, 10000), 0);
assert.ok(Math.abs(stressTrade(100, 110, 10, .01, .5, .1, 20).net + 575.5) < 1e-6);
const exits = exitPrices(100, 10, 10, .01, 50, 100);
assert.ok(Math.abs(exits.breakEven * 10 * .99 - 1010) < 1e-6);
assert.ok(Math.abs(exits.takeProfit * 10 * .99 - 1060) < 1e-6);
assert.equal(exitPrices(100, 0, 10, .01, 50, 100), null);
const tree = [{ itemId: "A", name: "A", amount: 2, source: "Craft", total: 50, children: [{ total: 50 }] }, { itemId: "B", name: "B", amount: 1, source: "Unknown", total: null, children: [] }];
assert.deepEqual(shoppingList(tree, 3).map(x => [x.amount, x.cost]), [[6, 150], [3, null]]);
assert.deepEqual(productionPlan(100, 20, 12, 5, 1, 250), { slots: 2, cycles: 2, capital: 200, profit: 80 });
assert.equal(productionPlan(100, 20, 0, 5, 1, 250).cycles, 0);
assert.deepEqual(fuelReturn(100, .25, 24, 700, 2), { extra: 1200, cost: 1400, net: -200, maxFuelPrice: 600 });
assert.equal(harvestIncome(1000, 10, .01, 100), 9800);
assert.equal(harvestIncome(1000, null, .01, 100), null);
assert.equal(lootPlan(1000, 0, 10, 100, 0, 5).net, -1000);
assert.equal(lootPlan(1000, 0, 10, 100, 0, 5).noDrop, 1);
assert.equal(lootPlan(1000, 1, 10, 100, 0, 5).runsFor95, 1);
const loot = lootPlan(1000, .01, 100, 50, 20, 5);
assert.equal(loot.bankroll, 5000);
assert.ok((1 - .01) ** loot.runsFor95 <= .05);
assert.ok((1 - .01) ** (loot.runsFor95 - 1) > .05);
assert.equal(lootPlan(1000, .01, 100, 50, 20, 0).hourly, null);
const freshness = { stale: false };
assert.equal(opportunities({ freshness, flips: [{ manipulated: true }] }).length, 0);
const crafts = opportunities(undefined, { freshness, flips: [{ itemId: "X", name: "X", outputCount: 4, materialCost: 100, craftCost: 10, expectedProfit: 20, roi: .18, salesPerDay: 12, confidence: { score: .8 }, requirement: "Collection" }] });
assert.equal(crafts[0].limit, 3);
assert.equal(crafts[0].cost, 110);
assert.equal(allocate(crafts, 1000, 0, 1, 5).spent, 0);
console.log("Money workbench passed: fees, capital limits, duplicate exposure, stale/locked recipes, volume, stress, production, unknown prices and independent drop risk.");
