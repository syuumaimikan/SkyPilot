import assert from 'node:assert/strict';
import {blankLab,decodeLab,combatPlan,runPlan,inventoryPlan,upgradePlan} from '../apps/web/lib/play-lab.ts';

assert.deepEqual(combatPlan(1000,120,2,100,20,500,80),{hits:9,dps:240,seconds:1000/240,survival:12.5,casts:6});
assert.equal(combatPlan(100,0,0,0,0,0,0).seconds,null);
assert.equal(combatPlan(100,1,1,10,20,10,0).survival,null);
assert.equal(combatPlan(0,0,0,1,0,0,1).hits,0);
assert.deepEqual(runPlan(5,1,11,1000,100,200,2),{runs:2,used:11,spare:0,bankroll:400,net:1600,perPlayer:800,hourly:1600*60/11});
assert.equal(runPlan(5,1,10,1000,100,200,1).runs,1);
assert.equal(runPlan(5,1,4,1000,100,200,1).net,0);
assert.equal(runPlan(5,0,10,100,200,0,1).net,-200);
const supply = {id:'one',name:'Item',quantity:1,perRun:2,owned:3,stack:64,price:10};
