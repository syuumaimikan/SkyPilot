assert.equal(inv.items[0].required,65);assert.equal(inv.items[0].missing,62);assert.equal(inv.items[0].slots,2);
assert.equal(inv.used,3);assert.equal(inv.overflow,2);assert.equal(inv.cost,620);assert.equal(inv.trips,3);
assert.equal(inventoryPlan([supply],0,1).trips,null);
assert.equal(inventoryPlan([{...supply,price:0}],36,10).unpriced,1);
const upgrade = upgradePlan(100,120,1000,5,4,10,6000);
assert.equal(upgrade.gain,20);assert.equal(upgrade.percent,20);assert.equal(upgrade.savedMinutes,10);assert.equal(upgrade.paybackRuns,10);
assert.equal(upgradePlan(0,0,10,4,5,10,6000).paybackRuns,null);
assert.equal(upgradePlan(0,0,0,5,5,10,0).paybackRuns,0);
