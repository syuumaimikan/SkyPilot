// Post-processes ts-rs output:
//  * 64-bit integers are emitted as `bigint`, but serde_json sends them as JSON numbers and
//    every value SkyPilot exchanges is far below 2^53, so they are typed as `number`.
//  * writes src/index.ts re-exporting every generated type.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src");
const gen = join(root, "generated");
const names = [];
for (const file of readdirSync(gen, { withFileTypes: true })) {
  if (!file.isFile() || !file.name.endsWith(".ts")) continue;
  const path = join(gen, file.name);
  const src = readFileSync(path, "utf8");
  const out = src.replace(/\bbigint\b/g, "number");
  if (out !== src) writeFileSync(path, out);
  names.push(file.name.slice(0, -3));
}
names.sort();
const index =
  "// Generated by scripts/postprocess.mjs - do not edit.\n" +
  names.map((n) => `export type { ${n} } from "./generated/${n}";`).join("\n") +
  "\n";
writeFileSync(join(root, "index.ts"), index);
console.log(`postprocessed ${names.length} types`);
